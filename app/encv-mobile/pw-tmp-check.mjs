import { chromium } from "@playwright/test";
const b = await chromium.launch({ executablePath: "/usr/bin/chromium", args: ["--no-sandbox", "--disable-dev-shm-usage"] });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
p.on("console", m => { if (m.type() === "error") errs.push(m.text().slice(0, 300)); });
p.on("pageerror", e => errs.push("pageerror: " + String(e).slice(0, 300)));
await p.goto("http://127.0.0.1:16666/tabs/files", { waitUntil: "domcontentloaded", timeout: 60000 });
await p.waitForTimeout(4000);
const info = await p.evaluate(() => ({ items: document.querySelectorAll("#main-content ion-list ion-item").length, split: !!document.querySelector(".files-split"), detail: !!document.querySelector("[data-testid=files-detail]"), text: (document.body.innerText || "").slice(0, 200).replace(/\s+/g, " ") }));
console.log(JSON.stringify(info));
console.log(JSON.stringify(errs.slice(0, 5), null, 1));
await b.close();
